import XCTest
@testable import InspectorCore

final class BranchHistoryTests: XCTestCase {
    let base: [[String: Any]] = [
        ["role": "system", "content": "Instructions"], ["role": "user", "content": "Review the project"]
    ]
    let exchange: [[String: Any]] = [
        [
            "role": "assistant",
            "tool_calls": [
                [
                    "id": "review-call", "type": "function",
                    "function": ["name": "terminal", "arguments": "{\"command\":\"date\"}"]
                ]
            ]
        ],
        ["role": "tool", "tool_call_id": "review-call", "content": "Original result"]
    ]
    let answer: [[String: Any]] = [["role": "assistant", "content": "Review complete"]]
    let notification =
        "[IMPORTANT: Background process proc_test completed normally (exit code 0).\nOutput: already finished]\n\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input.]"
    func request(_ messages: [[String: Any]], temperature: Double = 0.5) throws -> String {
        let data = try JSONSerialization.data(
            withJSONObject: ["model": "test", "messages": messages, "tools": [], "temperature": temperature],
            options: [.sortedKeys])
        return
            "2026-11-21 10:00:00,000 - omlx.server - TRACE - [-] - Incoming POST /v1/chat/completions — body: \(String(decoding: data, as: UTF8.self))\n"
    }
    func temp(_ text: String) throws -> URL {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("branch-history-\(UUID()).log")
        try Data(text.utf8).write(to: url)
        addTeardownBlock { try? FileManager.default.removeItem(at: url) }
        return url
    }
    func requests(_ s: LogSnapshot) -> [InspectorEvent] {
        s.turns.flatMap(\.events).filter { $0.kind == .request }.sorted {
            $0.evidence.source.offset < $1.evidence.source.offset
        }
    }
    func testSiblingNotificationReusesAncestorWithoutDuplicatingTools() throws {
        let prior = base + exchange
        let skill = prior + answer + [["role": "user", "content": "Update skills"]]
        let notify = prior + answer + [["role": "user", "content": notification]]
        let next = notify + [["role": "assistant", "content": "Acknowledged"], ["role": "user", "content": "Thanks"]]
        let s = try LogReader.load(
            temp(request(base) + request(prior) + request(skill, temperature: 0.9) + request(notify) + request(next)))
        XCTAssertEqual(Set(s.turns.map(\.group)).count, 1)
        XCTAssertEqual(s.requestCount, 5)
        XCTAssertEqual(s.callCount, 1)
        let results = s.turns.flatMap(\.events).filter { $0.kind == .result }
        XCTAssertEqual(results.count, 1)
        XCTAssertNotNil(results[0].linkedEvent)
        let events = requests(s)
        XCTAssertEqual(events[3].metrics?.previousRequest, events[1].id)
        XCTAssertEqual(events[3].metrics?.changedFields, [])  // Compare the ancestor, not the sibling's settings.
        XCTAssertEqual(events[3].continuation?.retainedMessages, 4)
        XCTAssertEqual(events[3].continuation?.reason, "Responding to a background-process notification")
        XCTAssertEqual(events[4].continuation?.reason, "Responding to a new user message")
        XCTAssertEqual(events[4].metrics?.previousRequest, events[3].id)
        let turn = try XCTUnwrap(s.turns.first { $0.title == "Background process notification · proc_test" })
        XCTAssertEqual(turn.requestCount, 1)
        XCTAssertEqual(turn.callCount, 0)
        XCTAssertEqual(turn.timelineCycles(showContext: false).flatMap(\.events).count, 2)
        let detail = try LogReader.detail(events[3], snapshot: s)
        XCTAssertTrue(detail.raw.contains("review-call"))
        XCTAssertTrue(detail.structured.contains("Original result"))
        XCTAssertNotNil(detail.tree)
        XCTAssertTrue(detail.readable.contains("6 total, 2 newly introduced, 4 retained"))
    }
    func testPartialLiveBranchAndClearDisplayAgreeWithFullIndex() throws {
        let prior = base + exchange
        let prefix =
            try request(base) + request(prior)
            + request(prior + answer + [["role": "user", "content": "Update skills"]])
        let url = try temp(prefix)
        var index = LogIndex(url: url)
        let before = try XCTUnwrap(index.refresh()).snapshot
        let boundary = DisplayBoundary(snapshot: before)
        let suffix = Data(try request(prior + answer + [["role": "user", "content": notification]]).utf8)
        let file = try FileHandle(forWritingTo: url)
        defer { try? file.close() }
        try file.seekToEnd()
        let split = suffix.count / 2
        try file.write(contentsOf: suffix.prefix(split))
        _ = try index.refresh()
        try file.write(contentsOf: suffix.dropFirst(split))
        let live = try XCTUnwrap(index.refresh()).snapshot
        let full = try LogReader.load(url)
        XCTAssertEqual(live.turns.map(\.id), full.turns.map(\.id))
        XCTAssertEqual(live.turns.flatMap(\.events).map(\.id), full.turns.flatMap(\.events).map(\.id))
        XCTAssertEqual(live.callCount, 1)
        let visible = boundary.applying(to: live)
        XCTAssertEqual(visible.requestCount, 1)
        XCTAssertEqual(visible.callCount, 0)
        XCTAssertEqual(visible.turns.flatMap(\.events).filter { $0.kind == .result }.count, 0)
        XCTAssertEqual(requests(live).last?.metrics?.previousRequest, requests(full).last?.metrics?.previousRequest)
    }
    func testRepeatedRichHistoryKeepsOneOriginForLaterContinuation() throws {
        let prior = base + exchange
        let s = try LogReader.load(
            temp(
                request(base) + request(prior) + request(prior)
                    + request(prior + answer + [["role": "user", "content": notification]])))
        let last = try XCTUnwrap(requests(s).last)
        let events = requests(s)
        XCTAssertEqual(events[2].continuation?.retainedMessages, 4)
        XCTAssertEqual(events[2].continuation?.reason, "Repeated request history (retry or replay)")
        XCTAssertEqual(events[2].metrics?.previousRequest, events[1].id)
        XCTAssertEqual(last.continuation?.retainedMessages, 4)
        XCTAssertEqual(last.metrics?.previousRequest, events[2].id)
        XCTAssertEqual(Set(s.turns.map(\.group)).count, 1)
        XCTAssertEqual(s.callCount, 1)
    }
    func testIdenticalOpeningPromptsRemainSeparateAndAmbiguousDescendantDoesNotMerge() throws {
        let s = try LogReader.load(temp(request(base) + request(base) + request(base + exchange)))
        let events = requests(s)
        XCTAssertEqual(Set(s.turns.map(\.group)).count, 3)
        XCTAssertNil(events.last?.continuation?.retainedMessages)
        XCTAssertTrue(events.last?.continuation?.explanation?.contains("No unique predecessor") == true)
    }
    func testInterleavedStreamsAndReplayedOldCheckpointKeepTheirOwnHistories() throws {
        let other: [[String: Any]] = [["role": "user", "content": "Independent stream"]]
        let rich = base + exchange
        let later = rich + answer + [["role": "user", "content": "Follow up"]]
        let s = try LogReader.load(
            temp(
                request(base) + request(other) + request(rich) + request(later)
                    + request(other + [["role": "assistant", "content": "Other answer"]]) + request(rich)
                    + request(rich + answer)))
        let events = requests(s)
        XCTAssertEqual(Set(s.turns.map(\.group)).count, 2)
        XCTAssertEqual(events[5].metrics?.previousRequest, events[2].id)
        XCTAssertEqual(events[6].metrics?.previousRequest, events[5].id)
        XCTAssertEqual(s.callCount, 1)
        XCTAssertEqual(s.requestCount, 7)
    }
    func testRewrittenToolHistoryOffersComparisonWithoutMerging() throws {
        let rich = base + exchange
        var changed = rich
        changed[3]["content"] = "Compacted terminal result"
        let s = try LogReader.load(temp(request(rich) + request(changed)))
        let events = requests(s)
        XCTAssertNotEqual(s.turns.first?.group, s.turns.last?.group)
        XCTAssertTrue(events[1].metrics?.possibleReset == true)
        XCTAssertEqual(events[1].metrics?.previousRequest, events[0].id)
        XCTAssertNil(events[1].continuation?.retainedMessages)
    }
    func testChangedHistoryAndOrdinaryBackgroundTextAreNotMergedOrRelabeled() throws {
        let prior = base + exchange
        var changed = prior
        changed[0]["content"] = "Different instructions"
        let ordinary = "[IMPORTANT: Background process proc_test completed normally (exit code 0).]"
        let s = try LogReader.load(temp(request(prior) + request(changed + [["role": "user", "content": ordinary]])))
        XCTAssertEqual(s.callCount, 2)  // Same tool ID alone cannot establish a shared history.
        XCTAssertNotEqual(s.turns.first?.group, s.turns.last?.group)
        XCTAssertFalse(s.turns.last?.title.hasPrefix("Background process notification") ?? true)
        XCTAssertEqual(requests(s).last?.continuation?.reason, "Starting this turn")
    }
    func testAncestorsRetainCompactCheckpointsAndOnlyHeadsKeepMessageHashes() throws {
        var builder = EvidenceBuilder()
        var messages = base
        for i in 0..<100 {
            let text = try request(messages)
            let body = String(text[text.range(of: "Incoming POST")!.lowerBound...])
            try builder.request(
                LogRecord(
                    source: SourceRef(offset: UInt64(i), length: text.utf8.count, line: i + 1, endLine: i + 1),
                    timestamp: "2026-11-21 10:00:00,000", logger: "omlx.server", level: "TRACE", body: body))
            messages.append(["role": "assistant", "content": "Step \(i)"])
        }
        XCTAssertEqual(builder.histories.count, 100)
        XCTAssertEqual(builder.historyChains.count, 100)
        XCTAssertEqual(builder.histories.filter { $0.headHashes != nil }.count, 1)
        XCTAssertEqual(builder.historiesByUser.values.flatMap { $0 }.count, 1)
    }
    func testCompressedToolHistoryDoesNotReattachThroughAnOldOpening() throws {
        let prior = base + exchange
        let skill = prior + answer + [["role": "user", "content": "Update skills"]]
        var compressed = prior
        compressed[3]["content"] = "[terminal] compacted result"
        compressed += [["role": "user", "content": "Follow up"]]
        let s = try LogReader.load(temp(request(base) + request(prior) + request(skill) + request(compressed)))
        XCTAssertEqual(s.turns[0].callCount, 1)
        XCTAssertNotEqual(s.turns.first?.group, s.turns.last?.group)
        XCTAssertNil(requests(s).last?.continuation?.retainedMessages)
        XCTAssertNil(requests(s).last?.metrics?.previousRequest)
    }
}
