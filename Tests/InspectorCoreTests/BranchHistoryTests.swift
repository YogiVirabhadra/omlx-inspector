import XCTest
@testable import InspectorCore

final class BranchHistoryTests: XCTestCase {
    let base: [[String: Any]] = [["role": "system", "content": "Instructions"], ["role": "user", "content": "Review the project"]]
    let exchange: [[String: Any]] = [
        ["role": "assistant", "tool_calls": [["id": "review-call", "type": "function", "function": ["name": "terminal", "arguments": "{\"command\":\"date\"}"]]]],
        ["role": "tool", "tool_call_id": "review-call", "content": "Original result"]
    ]
    let answer: [[String: Any]] = [["role": "assistant", "content": "Review complete"]]
    let notification = "[IMPORTANT: Background process proc_test completed normally (exit code 0).\nOutput: already finished]\n\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input.]"
    func request(_ messages: [[String: Any]], temperature: Double = 0.5) throws -> String {
        let data = try JSONSerialization.data(withJSONObject: ["model": "test", "messages": messages, "tools": [], "temperature": temperature], options: [.sortedKeys])
        return "2026-11-21 10:00:00,000 - omlx.server - TRACE - [-] - Incoming POST /v1/chat/completions — body: \(String(decoding: data, as: UTF8.self))\n"
    }
    func temp(_ text: String) throws -> URL {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("branch-history-\(UUID()).log")
        try Data(text.utf8).write(to: url)
        addTeardownBlock { try? FileManager.default.removeItem(at: url) }
        return url
    }
    func requests(_ s: LogSnapshot) -> [InspectorEvent] {
        s.turns.flatMap(\.events).filter { $0.kind == .request }.sorted { $0.evidence.source.offset < $1.evidence.source.offset }
    }
    func testSiblingNotificationReusesAncestorWithoutDuplicatingTools() throws {
        let prior = base + exchange
        let skill = prior + answer + [["role": "user", "content": "Update skills"]]
        let notify = prior + answer + [["role": "user", "content": notification]]
        let next = notify + [["role": "assistant", "content": "Acknowledged"], ["role": "user", "content": "Thanks"]]
        let s = try LogReader.load(temp(request(base) + request(prior) + request(skill, temperature: 0.9) + request(notify) + request(next)))
        XCTAssertEqual(Set(s.turns.map(\.group)).count, 1)
        XCTAssertEqual(s.requestCount, 5); XCTAssertEqual(s.callCount, 1)
        let results = s.turns.flatMap(\.events).filter { $0.kind == .result }
        XCTAssertEqual(results.count, 1); XCTAssertNotNil(results[0].linkedEvent)
        let events = requests(s)
        XCTAssertEqual(events[3].metrics?.previousRequest, events[1].id)
        XCTAssertEqual(events[3].metrics?.changedFields, []) // Compare the ancestor, not the sibling's settings.
        XCTAssertEqual(events[3].continuation?.retainedMessages, 4)
        XCTAssertEqual(events[3].continuation?.reason, "Responding to a background-process notification")
        XCTAssertEqual(events[4].continuation?.reason, "Responding to a new user message")
        XCTAssertEqual(events[4].metrics?.previousRequest, events[3].id)
        let turn = try XCTUnwrap(s.turns.first { $0.title == "Background process notification · proc_test" })
        XCTAssertEqual(turn.requests, 1); XCTAssertEqual(turn.calls, 0)
        XCTAssertEqual(turn.timelineCycles(showContext: false).flatMap(\.events).count, 2)
        let detail = try LogReader.detail(events[3], snapshot: s)
        XCTAssertTrue(detail.raw.contains("review-call")); XCTAssertTrue(detail.structured.contains("Original result"))
        XCTAssertNotNil(detail.tree)
        XCTAssertTrue(detail.readable.contains("6 total, 2 newly introduced, 4 retained"))
    }
    func testPartialLiveBranchAndClearDisplayAgreeWithFullIndex() throws {
        let prior = base + exchange
        let prefix = try request(base) + request(prior) + request(prior + answer + [["role": "user", "content": "Update skills"]])
        let url = try temp(prefix); var index = LogIndex(url: url)
        let before = try XCTUnwrap(index.refresh()).snapshot
        let boundary = DisplayBoundary(snapshot: before)
        let suffix = Data(try request(prior + answer + [["role": "user", "content": notification]]).utf8)
        let file = try FileHandle(forWritingTo: url); defer { try? file.close() }
        try file.seekToEnd()
        let split = suffix.count / 2
        try file.write(contentsOf: suffix.prefix(split)); _ = try index.refresh()
        try file.write(contentsOf: suffix.dropFirst(split))
        let live = try XCTUnwrap(index.refresh()).snapshot, full = try LogReader.load(url)
        XCTAssertEqual(live.turns.map(\.id), full.turns.map(\.id))
        XCTAssertEqual(live.turns.flatMap(\.events).map(\.id), full.turns.flatMap(\.events).map(\.id))
        XCTAssertEqual(live.callCount, 1)
        let visible = boundary.applying(to: live)
        XCTAssertEqual(visible.requestCount, 1); XCTAssertEqual(visible.callCount, 0)
        XCTAssertEqual(visible.turns.flatMap(\.events).filter { $0.kind == .result }.count, 0)
        XCTAssertEqual(requests(live).last?.metrics?.previousRequest, requests(full).last?.metrics?.previousRequest)
    }
    func testAmbiguousLongestAncestorDoesNotFallBackToShorterMatch() throws {
        let prior = base + exchange
        let s = try LogReader.load(temp(request(base) + request(prior) + request(prior) + request(prior + answer + [["role": "user", "content": notification]])))
        let last = try XCTUnwrap(requests(s).last)
        XCTAssertNil(last.continuation?.retainedMessages)
        XCTAssertNil(last.metrics?.previousRequest)
        XCTAssertNotEqual(s.turns.first?.group, s.turns.last?.group)
    }
    func testChangedHistoryAndOrdinaryBackgroundTextAreNotMergedOrRelabeled() throws {
        let prior = base + exchange
        var changed = prior
        changed[0]["content"] = "Different instructions"
        let ordinary = "[IMPORTANT: Background process proc_test completed normally (exit code 0).]"
        let s = try LogReader.load(temp(request(prior) + request(changed + [["role": "user", "content": ordinary]])))
        XCTAssertEqual(s.callCount, 2) // Same tool ID alone cannot establish a shared history.
        XCTAssertNotEqual(s.turns.first?.group, s.turns.last?.group)
        XCTAssertFalse(s.turns.last?.title.hasPrefix("Background process notification") ?? true)
        XCTAssertEqual(requests(s).last?.continuation?.reason, "Starting this turn")
    }
    func testAncestorsRetainCompactCheckpointsAndOnlyHeadsKeepMessageHashes() throws {
        var builder = EvidenceBuilder(), messages = base
        for i in 0..<100 {
            let text = try request(messages)
            let body = String(text[text.range(of: "Incoming POST")!.lowerBound...])
            try builder.request(LogRecord(source: SourceRef(offset: UInt64(i), length: text.utf8.count, line: i + 1, endLine: i + 1), timestamp: "2026-11-21 10:00:00,000", logger: "omlx.server", level: "TRACE", body: body))
            messages.append(["role": "assistant", "content": "Step \(i)"])
        }
        XCTAssertEqual(builder.histories.count, 100)
        XCTAssertEqual(builder.historyChains.count, 100)
        XCTAssertEqual(builder.histories.filter { $0.headHashes != nil }.count, 1)
        XCTAssertEqual(builder.historiesByUser.values.flatMap { $0 }.count, 1)
    }
    func testCompressedToolHistoryDoesNotReattachThroughAnOldOpening() throws {
        let prior = base + exchange
        let skill = prior + answer + [["role": "user", "content": "Update skills"]]
        var compressed = prior
        compressed[3]["content"] = "[terminal] compacted result"
        compressed += [["role": "user", "content": "Follow up"]]
        let s = try LogReader.load(temp(request(base) + request(prior) + request(skill) + request(compressed)))
        XCTAssertEqual(s.turns[0].calls, 1)
        XCTAssertNotEqual(s.turns.first?.group, s.turns.last?.group)
        XCTAssertNil(requests(s).last?.continuation?.retainedMessages)
        XCTAssertNil(requests(s).last?.metrics?.previousRequest)
    }
    func testActualReviewNotificationRetainsAllEvidenceWithoutDuplicatingCalls() throws {
        guard let path = ProcessInfo.processInfo.environment["INSPECTOR_COMPLETION_LOG"] else { throw XCTSkip("Enable native completion log checks") }
        let s = try LogReader.load(URL(fileURLWithPath: path))
        let original = try XCTUnwrap(s.turns.first { $0.requests == 42 && $0.title.hasPrefix("Please do a careful code review") })
        let notification = try XCTUnwrap(s.turns.first { $0.title == "Background process notification · proc_83ecb8f3fb31" })
        XCTAssertEqual(notification.group, original.group)
        XCTAssertEqual(notification.requests, 1); XCTAssertEqual(notification.calls, 0)
        XCTAssertFalse(notification.events.contains { $0.kind == .result })
        XCTAssertEqual(s.turns.filter { $0.group == original.group && $0.title == original.title }.count, 1)
        XCTAssertEqual(original.calls, 61)
        let originalCalls = Set(original.events.filter { $0.kind == .call }.compactMap(\.toolID))
        let conversationCalls = s.turns.filter { $0.group == original.group }.flatMap(\.events).filter { $0.kind == .call && originalCalls.contains($0.toolID ?? "") }
        XCTAssertEqual(conversationCalls.count, 61)
        let event = try XCTUnwrap(notification.events.first { $0.kind == .request })
        XCTAssertEqual(event.continuation?.retainedMessages, 104)
        XCTAssertEqual(event.continuation?.totalMessages, 106)
        XCTAssertEqual(event.metrics?.previousRequest, original.events.last { $0.kind == .request }?.id)
        let detail = try LogReader.detail(event, snapshot: s)
        XCTAssertTrue(detail.readable.contains("106 total, 2 newly introduced, 104 retained"))
        let object = try XCTUnwrap(JSONSerialization.jsonObject(with: Data(detail.structured.utf8)) as? [String: Any])
        let messages = try XCTUnwrap(object["messages"] as? [[String: Any]])
        XCTAssertEqual(messages.flatMap { $0["tool_calls"] as? [Any] ?? [] }.count, 61)
        XCTAssertEqual(messages.filter { $0["role"] as? String == "tool" }.count, 61)
        XCTAssertTrue(detail.raw.contains("proc_83ecb8f3fb31")); XCTAssertNotNil(detail.tree)
        XCTAssertEqual(original.events.last { $0.kind == .request }?.completion?.finishReason, "stop")
        XCTAssertEqual(original.metrics.peakPromptTokens, 179590)
        XCTAssertEqual(original.metrics.elapsedSeconds ?? 0, 1710.846, accuracy: 0.001)
    }
}
